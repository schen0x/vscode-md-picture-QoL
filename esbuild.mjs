import { build } from 'esbuild';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve, join } from 'node:path';
const common = { bundle: true, platform: 'node', format: 'cjs', target: 'node20', sourcemap: true, external: ['vscode'] };
const extension = await build({ ...common, entryPoints: ['src/extension.ts'], outfile: 'dist/extension.cjs', metafile: true });
const imageWorker = await build({ ...common, entryPoints: ['src/image-worker.ts'], outfile: 'dist/image-worker.cjs', metafile: true });

// The VSIX bundles runtime dependencies, so ship their original license notices too.
const packages = new Set();
for (const input of new Set([...Object.keys(extension.metafile.inputs), ...Object.keys(imageWorker.metafile.inputs)])) {
  if (!input.includes('node_modules/')) continue;
  let directory = dirname(resolve(input));
  while (directory !== dirname(directory)) {
    try {
      await readFile(join(directory, 'package.json'));
      packages.add(directory);
      break;
    } catch { directory = dirname(directory); }
  }
}
const notices = [];
for (const directory of packages) {
  const pkg = JSON.parse(await readFile(join(directory, 'package.json'), 'utf8'));
  const files = (await readdir(directory)).filter(name => /^licen[cs]e(?:[.-]|$)/i.test(name)).sort();
  if (!files.length) throw new Error(`Missing license notice for bundled dependency ${pkg.name}`);
  const licenses = await Promise.all(files.map(file => readFile(join(directory, file), 'utf8')));
  // jpeg-js also embeds upstream encoder/decoder notices absent from its root LICENSE.
  if (pkg.name === 'jpeg-js') {
    for (const file of ['lib/encoder.js', 'lib/decoder.js']) {
      const source = await readFile(join(directory, file), 'utf8');
      const copyright = source.indexOf('Copyright');
      const end = source.indexOf('*/', copyright);
      if (copyright < 0 || end < 0) throw new Error(`Missing upstream notice in jpeg-js/${file}`);
      licenses.push(source.slice(source.lastIndexOf('/*', copyright), end + 2));
    }
  }
  notices.push({ name: pkg.name, text: `## ${pkg.name} ${pkg.version}\n\n${licenses.join('\n\n').replace(/[\t ]+$/gm, '').trim()}\n` });
}
notices.sort((a, b) => a.name.localeCompare(b.name, 'en'));
await writeFile('THIRD_PARTY_NOTICES.md', '# Bundled dependency notices\n\nGenerated by `npm run compile` from the dependencies included in the extension.\n\n' + notices.map(notice => notice.text).join('\n'));

for (const name of await readdir('test')) {
  if (name.endsWith('.test.ts')) {
    await build({ ...common, alias: { vscode: './test/uiMock.ts' }, external: [], entryPoints: [`test/${name}`], outfile: `dist/test/${name.replace(/\.ts$/, '.cjs')}` });
  }
}
await build({ ...common, entryPoints: ['test/integration.ts'], outfile: 'dist/test/integration.cjs' });
// Test bundles resolve the same worker path relative to their own directory.
await writeFile('dist/test/image-worker.cjs', await readFile('dist/image-worker.cjs'));
